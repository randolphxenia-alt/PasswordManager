package com.passwordmanager.model;

/**
 * Состояние пароля записи после чтения из БД.
 */
public enum PasswordState {

    /** Пароль расшифрован и доступен для просмотра. */
    AVAILABLE,

    /** Пароль сохранён необратимым хешем: его можно только проверить. */
    HASHED,

    /** Данные повреждены и не расшифровываются. */
    CORRUPTED
}